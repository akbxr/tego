// Command genprices writes ../prices_gen.go, the built-in price table tego
// stats falls back to when it can't fetch the models.dev catalog.
//
//	go generate ./internal/stats              # fetches https://models.dev/api.json
//	go run ./internal/stats/genprices -in api.json
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strings"
	"time"

	"github.com/akbxr/tego/internal/stats"
)

func num(f float64) string {
	return strings.TrimSuffix(strings.TrimRight(fmt.Sprintf("%.6f", f), "0"), ".")
}

func literal(p stats.Price) string {
	s := fmt.Sprintf("{Input: %s, Output: %s", num(p.Input), num(p.Output))
	if p.CacheRead != 0 {
		s += ", CacheRead: " + num(p.CacheRead)
	}
	if p.CacheWrite != 0 {
		s += ", CacheWrite: " + num(p.CacheWrite)
	}
	if len(p.Tiers) > 0 {
		tiers := make([]string, len(p.Tiers))
		for i, t := range p.Tiers {
			tiers[i] = fmt.Sprintf("{Above: %d, Input: %s, Output: %s, CacheRead: %s, CacheWrite: %s}",
				t.Above, num(t.Input), num(t.Output), num(t.CacheRead), num(t.CacheWrite))
		}
		s += ", Tiers: []Tier{" + strings.Join(tiers, ", ") + "}"
	}
	return s + "}"
}

func main() {
	in := flag.String("in", "", "read the catalog from this file instead of "+stats.CatalogURL)
	out := flag.String("out", "prices_gen.go", "output file")
	flag.Parse()
	var data []byte
	var err error
	if *in != "" {
		data, err = os.ReadFile(*in)
	} else {
		var res *http.Response
		if res, err = http.Get(stats.CatalogURL); err == nil {
			defer res.Body.Close()
			if res.StatusCode != http.StatusOK {
				log.Fatalf("models.dev: %s", res.Status)
			}
			data, err = io.ReadAll(res.Body)
		}
	}
	if err != nil {
		log.Fatal(err)
	}
	prices, err := stats.ParseCatalog(data)
	if err != nil {
		log.Fatal(err)
	}
	keys := make([]string, 0, len(prices))
	for k := range prices {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	day := time.Now().Format("2006-01-02")
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by genprices from %s on %s; DO NOT EDIT.\n\npackage stats\n\nimport \"sync\"\n\n", stats.CatalogURL, day)
	fmt.Fprintf(&b, "// PricesDate is when the built-in prices were taken from models.dev.\nconst PricesDate = %q\n\n", day)
	b.WriteString("// builtinPrices returns API list prices in dollars per million tokens,\n// keyed by model id without a vendor prefix. The map is built on first\n// use, so tego runs that never price a request don't pay for it.\n")
	b.WriteString("var builtinPrices = sync.OnceValue(func() map[string]Price {\n\treturn map[string]Price{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t\t%q: %s,\n", k, literal(prices[k]))
	}
	b.WriteString("\t}\n})\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%s: %d models\n", *out, len(keys))
}
